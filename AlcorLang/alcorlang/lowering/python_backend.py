"""Lower ALCORCORE to a standalone Python program (spec section 7).

The generated file is the language runtime (``python_runtime.txt``) followed by one function per
PROGRAM block.  Each function is a ``while True`` loop with one ``if pc == N:`` arm per
instruction, so a backward jump is just an integer assignment.  The output must reproduce
``run()`` byte for byte on the conformance corpus, including trap text.

The generated code contains no ``eval``, ``exec`` or ``compile`` (spec section 8.4) and has no
effect authority: an EFFECT writes the same typed ``not_wired`` refusal receipt the conformance
interpreter writes.
"""

from __future__ import annotations

import functools
import json
import re
from pathlib import Path
from typing import Any

from ..core import compile_core
from ..errors import AlcorLangError

_RUNTIME_FILE = Path(__file__).with_name("python_runtime.txt")


@functools.cache
def _runtime_text() -> str:
    """Read the shared runtime that every lowered program starts with."""
    return _RUNTIME_FILE.read_text(encoding="utf-8").strip()


def _py_name(block_name: str | None, index: int) -> str:
    safe = re.sub(r"[^A-Za-z0-9_]", "_", block_name or "entry")
    return f"_p{index}_{safe}"


def lower_python(src: str, base_dir: str | None = None) -> str:
    """Lower a program to a standalone Python script.

    Run with ``python -I`` the script reads its input from stdin and writes exactly what
    ``run()`` returns.  A refused (unsigned ``complete``) program lowers to a script that prints
    the refusal line and does nothing else.

    Args:
        src: v1, v2 or v3 source.
        base_dir: The include root; ``None`` forbids INCLUDE.

    Returns:
        The Python source text.

    Raises:
        AlcorLangError: If the source is rejected at compile time.
    """
    core = compile_core(src, base_dir)
    lines = [
        "#!/usr/bin/env python3",
        "# Generated by alcorlang (AlcorLang v2). Do not edit.",
        f"# profile={core.profile} fuel={core.fuel}",
        _runtime_text(),
        "",
        f"_FUEL = {core.fuel}",
        "",
    ]
    if core.refused():
        lines += ["_sys.stdout.write('REFUSED unsigned_complete\\n')", ""]
        return "\n".join(lines) + "\n"

    ordered = [core.entry] + [b for b in core.blocks.values() if b is not core.entry]
    fnames = {}
    for idx, blk in enumerate(ordered):
        fnames[id(blk)] = _py_name(blk.name, idx)
    byname = {b.name: fnames[id(b)] for b in ordered if b.name}

    for blk in ordered:
        lines.append(f"def {fnames[id(blk)]}(fr):")
        lines.append("    pc = 0")
        lines.append("    while True:")
        lines.append("        _step()")
        for pc, ins in enumerate(blk.code):
            lines.append(f"        if pc == {pc}:")
            for body in _py_instr(ins, byname):
                lines.append("            " + body)
            if ins[0] not in ("JMP", "RET"):
                lines.append(f"            pc = {pc + 1}")
            lines.append("            continue")
        lines.append("        return 0")
        lines.append("")

    lines += [
        "def _main():",
        "    try:",
        f"        {fnames[id(core.entry)]}({{}})",
        "    except _Trap as _t:",
        "        _sys.stdout.write(_out() + 'TRAP %s\\n' % _t.code)",
        "        return",
        "    _sys.stdout.write(_out())",
        "",
        "_main()",
        "",
    ]
    return "\n".join(lines) + "\n"


def _py_instr(ins: tuple[Any, ...], byname: dict[str, str]) -> list[str]:
    op = ins[0]
    if op == "CONST":
        return [f"fr[{ins[1]!r}] = {ins[2]!r}"]
    if op == "MOV":
        return [f"fr[{ins[1]!r}] = _g(fr, {ins[2]!r})"]
    if op == "BINOP":
        return [f"fr[{ins[2]!r}] = _bin({ins[1]!r}, _g(fr, {ins[3]!r}), _g(fr, {ins[4]!r}))"]
    if op == "UNOP":
        return [f"fr[{ins[2]!r}] = _un({ins[1]!r}, _g(fr, {ins[3]!r}))"]
    if op == "JMP":
        return [f"pc = {ins[1]}"]
    if op == "JZ":
        return [f"if not _truth(_g(fr, {ins[1]!r})):", f"    pc = {ins[2]}", "    continue"]
    if op == "IO":
        if ins[1] == "emit":
            return [f"_TAPE.append(_render(_g(fr, {ins[3]!r})))"]
        return [f"_readline(fr, {ins[2]!r})"]
    if op == "EFFECT":
        return [f"_effect(fr, {json.dumps(ins[1], sort_keys=True)})"]
    if op == "CALL":
        args = ", ".join("{!r}: _g(fr, {!r})".format("$" + cell, reg) for cell, reg in ins[2])
        call = f"{byname[ins[1]]}({{{args}}})"
        if ins[3]:
            return [f"fr[{ins[3]!r}] = {call}"]
        return [call]
    if op == "RET":
        return [f"return _g(fr, {ins[1]!r})"] if ins[1] else ["return 0"]
    if op == "HALT":
        return ["return 0"]
    raise AlcorLangError(f"cannot lower instruction {op!r} to Python")

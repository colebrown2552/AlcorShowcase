"""Lower ALCORCORE to C99 (spec section 7): the same language on a bounded machine.

The typed static subset: ``int64`` with overflow traps (so a bounded machine stops instead of
wrapping), immutable length-prefixed strings (CAT allocates), static CALL targets, and IO on
stdin lines and a stdout tape.  EFFECT reserves the versioned ``alcor_gate_effect_v1`` byte ABI
but traps closed: native effects stay refused until a reviewed host shim exists.

The ``alc_*`` runtime in ``c_runtime.c`` has external linkage on purpose.  Every lowered unit
carries the whole runtime and defines its own ``main``, so two units were never linkable
together, and external linkage avoids ``-Wunused-function`` for programs that use no strings.
"""

from __future__ import annotations

import functools
import re
from pathlib import Path
from typing import Any

from ..core import Block, Core, compile_core
from ..errors import AlcorLangError

_RUNTIME_FILE = Path(__file__).with_name("c_runtime.c")
_GATE_EXTERN_FILE = Path(__file__).with_name("c_gate_extern.h")


@functools.cache
def _runtime_text() -> str:
    """Read the C runtime that every lowered unit starts with."""
    return _RUNTIME_FILE.read_text(encoding="utf-8").strip()


@functools.cache
def _gate_extern_text() -> str:
    """Read the reserved effect-gate ABI declaration."""
    return _GATE_EXTERN_FILE.read_text(encoding="utf-8").strip()


def _c_ident(name: str | None, index: int) -> str:
    safe = re.sub(r"[^A-Za-z0-9_]", "_", name or "entry")
    return f"p{index}_{safe}"


def _c_reg(reg: str) -> str:
    return ("c_" + reg[1:]) if reg.startswith("$") else ("t" + reg[1:])


def _c_string(text: str | None) -> str:
    if text is None:
        return "NULL"
    out = []
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char == '"':
            out.append('\\"')
        elif char == "\\":
            out.append("\\\\")
        elif char == "\n":
            out.append("\\n")
        elif char == "\t":
            out.append("\\t")
        elif 32 <= byte < 127:
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    return '"{}"'.format("".join(out))


_C_INT64_MIN = -(1 << 63)


_C_INT64_MAX = (1 << 63) - 1


def _validate_c_int64_literals(core: Core) -> None:
    if not (_C_INT64_MIN <= core.fuel <= _C_INT64_MAX):
        raise AlcorLangError(
            f"C backend fuel {core.fuel} is outside signed int64 range "
            f"[{_C_INT64_MIN}, {_C_INT64_MAX}]"
        )
    for block in [core.entry] + list(core.blocks.values()):
        for ins in block.code:
            if ins[0] != "CONST":
                continue
            literal = ins[2]
            if (
                isinstance(literal, int)
                and not isinstance(literal, bool)
                and not (_C_INT64_MIN <= literal <= _C_INT64_MAX)
            ):
                raise AlcorLangError(
                    f"C backend integer literal {literal} is outside signed int64 range "
                    f"[{_C_INT64_MIN}, {_C_INT64_MAX}]"
                )


def _c_val(lit: bool | int | str) -> str:
    if isinstance(lit, bool):
        return f"alc_bool({1 if lit else 0})"
    if isinstance(lit, int):
        if lit == _C_INT64_MIN:
            return "alc_int((-9223372036854775807LL - 1LL))"
        return f"alc_int({lit}LL)"
    byte_length = len(lit.encode("utf-8"))
    return f"alc_str({_c_string(lit)}, {byte_length}LL)"


def lower_c(src: str, base_dir: str | None = None) -> str:
    """Lower a program to a single C99 translation unit with its own ``main``.

    Args:
        src: v1, v2 or v3 source.
        base_dir: The include root; ``None`` forbids INCLUDE.

    Returns:
        The C source text.

    Raises:
        AlcorLangError: If the source is rejected, or a literal or the fuel does not fit in a
            signed 64-bit integer.
    """
    core = compile_core(src, base_dir)
    _validate_c_int64_literals(core)
    has_effect = any(
        ins[0] == "EFFECT" for blk in [core.entry, *core.blocks.values()] for ins in blk.code
    )
    out = [
        "/* Generated by alcorlang (AlcorLang v2). Do not edit.",
        f"   profile={core.profile} fuel={core.fuel} */",
        _runtime_text(),
        "",
    ]
    if has_effect:
        out += [_gate_extern_text(), ""]

    if core.refused():
        out += [
            "int main(void) {",
            '    printf("REFUSED unsigned_complete\\n");',
            "    return 0;",
            "}",
            "",
        ]
        return "\n".join(out) + "\n"

    ordered = [core.entry] + [b for b in core.blocks.values() if b is not core.entry]
    idents = {id(b): _c_ident(b.name, i) for i, b in enumerate(ordered)}
    byname = {b.name: (idents[id(b)], b) for b in ordered if b.name}
    out.append(f"static const long long ALC_FUEL = {core.fuel}LL;")
    out.append("")

    for blk in ordered:
        ident = idents[id(blk)]
        out.append("typedef struct {")
        for reg in blk.regs:
            field = _c_reg(reg)
            out.append(f"    Val {field}; int d_{field};")
        if not blk.regs:
            out.append("    int _unused;")
        out.append(f"}} Fr_{ident};")
        out.append(f"Val {ident}(Fr_{ident} *fr);")
        out.append("")

    for blk in ordered:
        ident = idents[id(blk)]
        out.append(f"Val {ident}(Fr_{ident} *fr) {{")
        out.append("    int pc = 0;")
        out.append("    for (;;) {")
        out.append("        alc_step(ALC_FUEL);")
        out.append("        switch (pc) {")
        for pc, ins in enumerate(blk.code):
            out.append(f"        case {pc}: {{")
            for line in _c_instr(ins, byname, idents):
                out.append("            " + line)
            if ins[0] not in ("JMP", "RET"):
                out.append(f"            pc = {pc + 1};")
            out.append("            continue;")
            out.append("        }")
        out.append("        default: return alc_int(0);")
        out.append("        }")
        out.append("    }")
        out.append("}")
        out.append("")

    entry_ident = idents[id(core.entry)]
    out += [
        "int main(void) {",
        f"    Fr_{entry_ident} fr;",
        "    memset(&fr, 0, sizeof fr);",
        "    alc_read_stdin();",
        f"    {entry_ident}(&fr);",
        "    alc_flush();",
        "    fflush(stdout);",
        "    return 0;",
        "}",
        "",
    ]
    return "\n".join(out) + "\n"


def _c_instr(
    ins: tuple[Any, ...], byname: dict[str, tuple[str, Block]], idents: dict[int, str]
) -> list[str]:
    op = ins[0]
    if op == "CONST":
        fld = _c_reg(ins[1])
        return [f"fr->{fld} = {_c_val(ins[2])}; fr->d_{fld} = 1;"]
    if op == "MOV":
        dst, src = _c_reg(ins[1]), _c_reg(ins[2])
        return [f"fr->{dst} = ALC_GET(fr, {src}); fr->d_{dst} = 1;"]
    if op == "BINOP":
        dst, lhs, rhs = _c_reg(ins[2]), _c_reg(ins[3]), _c_reg(ins[4])
        return [
            f'fr->{dst} = alc_bin("{ins[1]}", ALC_GET(fr, {lhs}), ALC_GET(fr, {rhs})); '
            f"fr->d_{dst} = 1;"
        ]
    if op == "UNOP":
        dst = _c_reg(ins[2])
        return [f'fr->{dst} = alc_un("{ins[1]}", ALC_GET(fr, {_c_reg(ins[3])})); fr->d_{dst} = 1;']
    if op == "JMP":
        return [f"pc = {ins[1]};"]
    if op == "JZ":
        return [f"if (!alc_truth(ALC_GET(fr, {_c_reg(ins[1])}))) {{ pc = {ins[2]}; continue; }}"]
    if op == "IO":
        if ins[1] == "emit":
            return [f"alc_emit(ALC_GET(fr, {_c_reg(ins[3])}));"]
        fld = _c_reg(ins[2])
        return [f"fr->{fld} = alc_readline(); fr->d_{fld} = 1;"]
    if op == "EFFECT":
        # C transport is specified but not admitted: it cannot yet construct the
        # same resolved canonical request bytes as the interpreter. Failing here
        # is safer than calling a shim with a subtly different contract.
        return ['alc_trap("effect_host_unavailable");']
    if op == "CALL":
        ident, blk = byname[ins[1]]
        lines = ["{", f"    Fr_{ident} sub;", "    memset(&sub, 0, sizeof sub);"]
        for cell, reg in ins[2]:
            fld = "c_" + cell
            lines.append(f"    sub.{fld} = ALC_GET(fr, {_c_reg(reg)}); sub.d_{fld} = 1;")
        if ins[3]:
            dst = _c_reg(ins[3])
            lines.append(f"    fr->{dst} = {ident}(&sub); fr->d_{dst} = 1;")
        else:
            lines.append(f"    {ident}(&sub);")
        lines.append("}")
        return lines
    if op == "RET":
        if ins[1]:
            return [f"return ALC_GET(fr, {_c_reg(ins[1])});"]
        return ["return alc_int(0);"]
    if op == "HALT":
        return ["return alc_int(0);"]
    raise AlcorLangError(f"cannot lower instruction {op!r} to C")
